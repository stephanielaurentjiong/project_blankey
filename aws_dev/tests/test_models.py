def test_anthropic_handler():
    """Test 2: Check if Anthropic handler builds correct payload."""
    print("\n" + "="*60)
    print("TEST 2: Anthropic Handler")
    print("="*60)
    
    try:
        # Create handler
        handler = AnthropicHandler()
        print("✅ Created AnthropicHandler instance")
        
        # Test payload building
        payload = handler.build_payload(
            image_b64="fake_base64_data_for_testing",
            image_mime="image/jpeg",
            prompt="Test prompt: describe this image",
            max_tokens=512,
            temperature=0.7
        )
        
        # Verify payload structure
        print("\n📋 Checking payload structure:")
        assert "anthropic_version" in payload, "Missing anthropic_version"
        print("   ✅ Has anthropic_version")
        
        assert "max_tokens" in payload, "Missing max_tokens"
        print("   ✅ Has max_tokens")
        
        assert "messages" in payload, "Missing messages array"
        print("   ✅ Has messages array")
        
        assert payload["messages"][0]["role"] == "user", "Wrong role"
        print("   ✅ Correct role: user")
        
        content = payload["messages"][0]["content"]
        assert len(content) == 2, "Should have 2 content blocks (image + text)"
        print("   ✅ Has 2 content blocks (image + text)")
        
        assert content[0]["type"] == "image", "First block should be image"
        print("   ✅ First block is image")
        
        assert content[1]["type"] == "text", "Second block should be text"
        print("   ✅ Second block is text")
        
        # Test response parsing
        print("\n📋 Testing response parsing:")
        mock_response = {
            "content": [
                {
                    "type": "text",
                    "text": "This is a test caption generated by Claude"
                }
            ]
        }
        
        result = handler.parse_response(mock_response)
        assert result == "This is a test caption generated by Claude"
        print(f"   ✅ Correctly parsed: '{result}'")
        
        print("\n✅ TEST 2 PASSED: Anthropic handler works!\n")
        return True
        
    except Exception as e:
        print(f"\n❌ TEST 2 FAILED: {e}\n")
        import traceback
        traceback.print_exc()
        return False

