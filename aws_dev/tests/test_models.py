def test_factory_pattern():
    """Test 4: Check if factory function creates correct handlers."""
    print("\n" + "="*60)
    print("TEST 4: Factory Pattern")
    print("="*60)
    
    try:
        # We'll test the factory logic directly without importing lambda_function
        # (lambda_function needs boto3 which isn't installed locally)
        
        print("\n📋 Testing factory logic manually:")
        
        # Test Claude handler creation logic
        print("\n   Testing Claude model:")
        config = get_model_config("claude-sonnet-4")
        provider = config["provider"]
        
        if provider == "anthropic":
            handler = AnthropicHandler()
            print(f"   ✅ Provider: {provider}")
            print(f"   ✅ Created: {type(handler).__name__}")
        else:
            raise ValueError(f"Wrong provider: {provider}")
        
        # Test QWen handler creation logic
        print("\n   Testing QWen model:")
        config = get_model_config("qwen-2.5-vl")
        provider = config["provider"]
        
        if provider == "qwen":
            handler = QwenHandler()
            print(f"   ✅ Provider: {provider}")
            print(f"   ✅ Created: {type(handler).__name__}")
        else:
            raise ValueError(f"Wrong provider: {provider}")
        
        # Test unsupported provider handling
        print("\n   Testing unsupported provider:")
        try:
            # Temporarily add a fake model with unsupported provider
            MODELS["test-fake"] = {"provider": "unsupported", "enabled": True}
            config = get_model_config("test-fake")
            provider = config["provider"]
            
            if provider == "anthropic":
                handler = AnthropicHandler()
            elif provider == "qwen":
                handler = QwenHandler()
            else:
                # This should happen for unsupported providers
                raise ValueError(f"No handler for provider: {provider}")
            
            print("   ❌ Should have raised an error!")
            
        except ValueError as e:
            print(f"   ✅ Correctly raised error for unsupported provider")
        finally:
            # Clean up the fake model
            if "test-fake" in MODELS:
                del MODELS["test-fake"]
        
        print("\n✅ TEST 4 PASSED: Factory pattern logic works!")
        print("   (Note: Skipped full lambda_function test - requires AWS boto3)\n")
        return True
        
    except Exception as e:
        print(f"\n❌ TEST 4 FAILED: {e}\n")
        import traceback
        traceback.print_exc()
        return False
    
